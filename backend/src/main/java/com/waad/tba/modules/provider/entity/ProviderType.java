package com.waad.tba.modules.provider.entity;

/**
 * Provider Type Enumeration
 * 
 * Represents different types of healthcare providers.
 */
public enum ProviderType {
    /**
     * مستشفى - Hospital
     */
    HOSPITAL,
    
    /**
     * عيادة تخصصية - Clinic
     */
    CLINIC,

    /**
     * عيادة أسنان - Dental Clinic
     */
    CLINIC_DEN,
    
    /**
     * مختبر تحاليل - Laboratory
     */
    LAB,
    
    /**
     * صيدلية - Pharmacy
     */
    PHARMACY,
    
    /**
     * مركز أشعة - Radiology
     */
    RADIOLOGY,

    /**
     * مركز علاج طبيعي - Physiotherapy
     */
    PHYSIOTHERAPY,

    /**
     * مركز بصريات وعيون - Optics / Ophthalmology
     */
    OPTICS
}
